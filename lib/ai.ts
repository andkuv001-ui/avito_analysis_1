export interface GeneratedReport {
  report: string;
  warnings: string[];
}

const REQUEST_TIMEOUT_MS = 90_000;
const INSIGHT_LINE_REGEX = /^\s*[-*]\s*Инсайт/;

interface ChatMessage {
  role: "system" | "user";
  content: string;
}

interface AiConfig {
  baseUrl: string;
  apiKey: string;
  model: string;
}

function getConfig(): AiConfig {
  const baseUrl = (
    process.env.ROUTERAI_BASE_URL ?? "https://routerai.ru/api/v1"
  ).replace(/\/+$/, "");
  const apiKey = process.env.ROUTERAI_API_KEY?.trim();
  const model = process.env.ROUTERAI_MODEL ?? "openai/gpt-4o-mini";

  if (!apiKey) {
    throw new Error("Не задан ROUTERAI_API_KEY");
  }
  return { baseUrl, apiKey, model };
}

async function requestCompletion(
  config: AiConfig,
  messages: ChatMessage[],
  temperature: number
): Promise<string> {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);

  try {
    const response = await fetch(`${config.baseUrl}/chat/completions`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${config.apiKey}`,
      },
      body: JSON.stringify({
        model: config.model,
        temperature,
        messages,
      }),
      signal: controller.signal,
      cache: "no-store",
    });

    if (!response.ok) {
      const detail = await response.text().catch(() => "");
      throw new Error(`AI API ${response.status}: ${detail.slice(0, 500)}`);
    }

    const data = (await response.json()) as {
      choices?: Array<{ message?: { content?: string } }>;
    };
    const content = data.choices?.[0]?.message?.content ?? "";
    if (!content.trim()) {
      throw new Error("AI вернул пустой ответ.");
    }
    return content.trim();
  } catch (error) {
    if (error instanceof Error && error.name === "AbortError") {
      throw new Error(
        `Превышено время ожидания AI (${REQUEST_TIMEOUT_MS / 1000} секунд).`
      );
    }
    throw error;
  } finally {
    clearTimeout(timer);
  }
}

function spliceInsight(draft: string, criticReply: string): string | null {
  const lines = draft.split("\n");
  const indices: number[] = [];
  lines.forEach((line, i) => {
    if (INSIGHT_LINE_REGEX.test(line)) indices.push(i);
  });
  if (indices.length === 0) return null;

  const insertAt = indices[0];
  const remove = new Set(indices);
  const kept = lines.filter((_, i) => !remove.has(i));
  const replacement = criticReply
    .split("\n")
    .filter((line) => line.trim().length > 0);
  kept.splice(insertAt, 0, ...replacement);
  return kept.join("\n");
}

export async function generateReport(
  metrics: AggregatedMetrics
): Promise<GeneratedReport> {
  const config = getConfig();
  const warnings: string[] = [];

  const draft = await requestCompletion(
    config,
    [
      { role: "system", content: SYSTEM_PROMPT },
      { role: "user", content: `Данные:\n${JSON.stringify(metrics)}` },
    ],
    0.3
  );

  let report = draft;
  try {
    const criticReply = await requestCompletion(
      config,
      [
        { role: "system", content: CRITIC_SYSTEM_PROMPT },
        {
          role: "user",
          content: `original_metrics:\n${JSON.stringify(
            metrics
          )}\n\ndraft_report:\n${draft}`,
        },
      ],
      0.2
    );
    const spliced = spliceInsight(draft, criticReply);
    if (spliced === null) {
      warnings.push(
        "Self-correction не выполнен: в черновике нет строк «Инсайт»."
      );
    } else {
      report = spliced;
    }
  } catch (error) {
    const reason =
      error instanceof Error ? error.message : "неизвестная ошибка";
    warnings.push(`Self-correction не выполнен: ${reason}`);
  }

  warnings.push(...validateReport(report, metrics));
  return { report, warnings };
}
